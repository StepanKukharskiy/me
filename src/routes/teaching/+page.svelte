<h1>Teaching &amp; research</h1>
<p class="lede">From procedural design to interactive tools, AI agents and reusable workflows.</p>
<p>
	I've spent more than a decade exploring how computational tools change professional design
	work—from parametric modeling and digital fabrication to interactive applications and AI agents.
	My current work focuses on turning familiar routines into executable AI jobs with clear inputs,
	editable outputs and explicit checks.
</p>

